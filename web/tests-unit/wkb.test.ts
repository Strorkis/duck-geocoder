// WKB の読み取りの単体テスト。`node --test tests-unit/` で流す (Node 24 は TypeScript をそのまま読む)。
// 見本は DuckDB の spatial で作った (`hex(ST_AsWKB(g))` と `ST_AsGeoJSON(g)`)。地図と DuckDB-WASM の
// 起動が要らないので、E2E ではなくここで確かめる。
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseWkb } from '../src/lib/wkb.ts';

const hex = (text: string) => Uint8Array.from(text.match(/../g)!.map((byte) => parseInt(byte, 16)));

const SAMPLES: [string, string, unknown][] = [
  ['点', '01010000006666666666766140CDCCCCCCCCCC4140', { type: 'Point', coordinates: [139.7, 35.6] }],
  [
    '線',
    '0102000000030000006666666666766140CDCCCCCCCCCC41409A999999997961409A99999999D94140CDCCCCCCCC7C61403333333333D34140',
    { type: 'LineString', coordinates: [[139.7, 35.6], [139.8, 35.7], [139.9, 35.65]] },
  ],
  [
    '穴のある面',
    '0103000000020000000500000000000000000000000000000000000000000000000000244000000000000000000000000000002440000000000000244000000000000000000000000000002440000000000000000000000000000000000400000000000000000000400000000000000040000000000000084000000000000000400000000000000840000000000000084000000000000000400000000000000040',
    {
      type: 'Polygon',
      coordinates: [
        [[0, 0], [10, 0], [10, 10], [0, 10], [0, 0]],
        [[2, 2], [3, 2], [3, 3], [2, 2]],
      ],
    },
  ],
  [
    '複数の面',
    '0106000000020000000103000000010000000400000000000000000000000000000000000000000000000000F03F0000000000000000000000000000F03F000000000000F03F000000000000000000000000000000000103000000010000000400000000000000000014400000000000001440000000000000184000000000000014400000000000001840000000000000184000000000000014400000000000001440',
    {
      type: 'MultiPolygon',
      coordinates: [[[[0, 0], [1, 0], [1, 1], [0, 0]]], [[[5, 5], [6, 5], [6, 6], [5, 5]]]],
    },
  ],
  [
    '複数の線',
    '01050000000200000001020000000200000000000000000000000000000000000000000000000000F03F000000000000F03F010200000003000000000000000000004000000000000000400000000000000840000000000000084000000000000010400000000000001040',
    { type: 'MultiLineString', coordinates: [[[0, 0], [1, 1]], [[2, 2], [3, 3], [4, 4]]] },
  ],
  [
    '複数の点',
    '0104000000020000000101000000000000000000F03F0000000000000040010100000000000000000008400000000000001040',
    { type: 'MultiPoint', coordinates: [[1, 2], [3, 4]] },
  ],
  [
    '寄せ集め',
    '0107000000020000000101000000000000000000F03F000000000000004001020000000200000000000000000000000000000000000000000000000000F03F000000000000F03F',
    {
      type: 'GeometryCollection',
      geometries: [
        { type: 'Point', coordinates: [1, 2] },
        { type: 'LineString', coordinates: [[0, 0], [1, 1]] },
      ],
    },
  ],
  [
    // ISO の Z (1003)。高さは読み飛ばす (地図は平面に描く)。
    '高さのある面 (ISO)',
    '01EB0300000100000004000000000000000000000000000000000000000000000000001440000000000000F03F00000000000000000000000000001440000000000000F03F000000000000F03F0000000000001440000000000000000000000000000000000000000000001440',
    { type: 'Polygon', coordinates: [[[0, 0], [1, 0], [1, 1], [0, 0]]] },
  ],
  [
    // ビッグエンディアン (先頭が 00)。DuckDB は書かないが、WKB としては正しい。
    'ビッグエンディアンの点',
    '0000000001406176666666666640' + '41CCCCCCCCCCCD',
    { type: 'Point', coordinates: [139.7, 35.6] },
  ],
  [
    // EWKB (PostGIS) の SRID 付き。SRID は読み飛ばす。
    'SRID 付きの点 (EWKB)',
    '0101000020E61000006666666666766140CDCCCCCCCCCC4140',
    { type: 'Point', coordinates: [139.7, 35.6] },
  ],
];

for (const [name, wkb, expected] of SAMPLES) {
  test(`WKB を読む: ${name}`, () => {
    assert.deepEqual(parseWkb(hex(wkb)), expected);
  });
}

test('配列の途中から始まるバイト列も読む (Arrow の列は大きなバッファの一部)', () => {
  const inner = hex(SAMPLES[0][1]);
  const buffer = new Uint8Array(inner.length + 7);
  buffer.set(inner, 7);
  assert.deepEqual(parseWkb(buffer.subarray(7)), SAMPLES[0][2]);
});

test('知らない型はエラーにする (黙って空にしない)', () => {
  assert.throws(() => parseWkb(hex('0109000000')), /読めません/);
});
